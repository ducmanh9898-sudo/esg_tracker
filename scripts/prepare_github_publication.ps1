param(
    [Parameter(Mandatory = $true)][string]$Destination
)
$ErrorActionPreference = 'Stop'
$taskSourceRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$taskPublishRoot = [IO.Path]::GetFullPath($Destination)
if ((Test-Path -LiteralPath $taskPublishRoot) -or $taskPublishRoot.StartsWith($taskSourceRoot + [IO.Path]::DirectorySeparatorChar)) {
    throw 'Publication destination must be NEW and outside the application directory.'
}
New-Item -ItemType Directory -Path $taskPublishRoot | Out-Null
$taskRootFiles = @('README.md', '.gitignore', 'app.py', 'requirements.txt', 'pytest.ini')
foreach ($taskName in $taskRootFiles) {
    Copy-Item -LiteralPath (Join-Path $taskSourceRoot $taskName) -Destination (Join-Path $taskPublishRoot $taskName)
}
$taskSourceDirectories = @('config', 'contracts', 'dashboard', 'src', 'scripts', 'tests', 'docs', 'knowledge_graph')
$taskExtensions = @('.py', '.js', '.cjs', '.css', '.svg', '.png', '.yml', '.yaml', '.json', '.sql', '.md', '.txt', '.ps1', '.ttl')
foreach ($taskFolder in $taskSourceDirectories) {
    foreach ($taskFile in Get-ChildItem -LiteralPath (Join-Path $taskSourceRoot $taskFolder) -Recurse -File) {
        $taskRelative = [IO.Path]::GetRelativePath($taskSourceRoot, $taskFile.FullName)
        if ($taskRelative -match '(^|[\\/])(__pycache__|node_modules|\.venv|\.pytest_cache|rendered[^\\/]*|output)([\\/]|$)') { continue }
        if ($taskFile.Extension -notin $taskExtensions) { continue }
        if ($taskFile.Name -match '^(\.env|credentials|service-account)' -or $taskFile.Length -gt 20MB) { continue }
        $taskTarget = Join-Path $taskPublishRoot $taskRelative
        New-Item -ItemType Directory -Path (Split-Path -Parent $taskTarget) -Force | Out-Null
        Copy-Item -LiteralPath $taskFile.FullName -Destination $taskTarget
    }
}
New-Item -ItemType Directory -Path (Join-Path $taskPublishRoot 'database') -Force | Out-Null
Copy-Item -LiteralPath (Join-Path $taskSourceRoot 'database\schema.sql') -Destination (Join-Path $taskPublishRoot 'database\schema.sql')
# Demo CSVs are generated by the app and are deliberately not published.
Write-Output "Prepared source-only publication: $taskPublishRoot"
